CREATE TABLE users (
  id BIGSERIAL PRIMARY KEY,
  email VARCHAR(255) UNIQUE NOT NULL,
  password VARCHAR(255) NOT NULL
);
CREATE TABLE expense (
  id BIGSERIAL PRIMARY KEY,
  title VARCHAR(100) NOT NULL,
  amount DOUBLE PRECISION NOT NULL,
  category VARCHAR(50),
  date DATE NOT NULL,
  user_id BIGINT REFERENCES users(id)
);